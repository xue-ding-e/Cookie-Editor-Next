import test from "node:test";
import assert from "node:assert/strict";
import {serializeNetscapeCookies} from "../src/utils/cookie_text_export.js";
import {parseCookieImport} from "../src/utils/cookie_text_import.js";

// Only synthetic in-memory objects are serialized and parsed; no Cookie API or file is accessed.
const url = "https://example.invalid/";
const fixture = {name: "fixture", value: "synthetic==", domain: "example.invalid", hostOnly: true, path: "/", secure: false, httpOnly: false, session: true};
const row = text => text.split("\n").at(-1).split("\t");

for (const expirationDate of [undefined, 0]) test(`session expiration ${expirationDate} stays zero in Netscape and absent after import`, () => {
    const text = serializeNetscapeCookies([{...fixture, expirationDate}]);
    assert.equal(row(text)[4], "0");
    assert.equal(Object.hasOwn(parseCookieImport(text, url)[0], "expirationDate"), false);
});

for (const expirationDate of [1893456000, 1893456000.625]) test(`persistent expiration ${expirationDate} retains the existing integer seconds representation`, () => {
    const text = serializeNetscapeCookies([{...fixture, session: false, expirationDate}]);
    assert.equal(row(text)[4], "1893456000");
    assert.equal(parseCookieImport(text, url)[0].expirationDate, 1893456000);
});

test("preserves HttpOnly, secure, domain flag, path and empty value", () => {
    const text = serializeNetscapeCookies([{...fixture, httpOnly: true, secure: true, domain: ".example.invalid", hostOnly: false, path: "/sub", value: ""}]);
    assert.deepEqual(row(text), ["#HttpOnly_.example.invalid", "TRUE", "/sub", "TRUE", "0", "fixture", ""]);
    assert.deepEqual(parseCookieImport(text, url), [{url, name: "fixture", value: "", httpOnly: true, secure: true, path: "/sub", domain: ".example.invalid"}]);
});

test("preserves header attribution and equals signs in values", () => {
    const text = serializeNetscapeCookies([fixture]);
    assert.ok(text.startsWith("# Netscape HTTP Cookie File\n# This file was generated by Cookie Editor https://chromewebstore.google.com/detail/cookie-editor/ookdjilphngeeeghgngjabigmpepanpl\n"));
    assert.equal(parseCookieImport(text, url)[0].value, "synthetic==");
});

test("does not mutate the supplied Cookie or infer a new lifetime from the clock", () => {
    const cookie = Object.freeze({...fixture});
    assert.equal(serializeNetscapeCookies(Object.freeze([cookie])), serializeNetscapeCookies([cookie]));
    assert.equal(Object.hasOwn(cookie, "expirationDate"), false);
});

test("keeps an empty list as a header-only export with no invented Cookie", () => {
    const text = serializeNetscapeCookies([]);
    assert.equal(text.split("\n").length, 2);
    assert.deepEqual(parseCookieImport(text, url), []);
});
