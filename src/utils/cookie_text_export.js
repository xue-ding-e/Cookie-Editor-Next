export const serializeNetscapeCookies = (cookies) => {
    let text = "# Netscape HTTP Cookie File\n# This file was generated by Cookie Editor https://chromewebstore.google.com/detail/cookie-editor/ookdjilphngeeeghgngjabigmpepanpl";
    for (const cookie of cookies) {
        // Chrome omits expirationDate for session Cookies; Netscape represents these with zero.
        // Do not invent a persistent lifetime when exporting a session Cookie.
        const expiration = cookie.expirationDate ? Number(String(cookie.expirationDate).split(".")[0]) : 0;
        text += `\n${cookie.httpOnly ? "#HttpOnly_" : ""}${cookie.domain}\t${String(cookie.domain.startsWith(".")).toUpperCase()}\t${cookie.path}\t${String(cookie.secure).toUpperCase()}\t${expiration}\t${cookie.name}\t${cookie.value}`;
    }
    return text;
};
